    fun toUnicode(name: String): String? {
        table[name]?.let { return it }
        val base = name.substringBefore('.')
        table[base]?.let { return it }
        Regex("^uni([0-9A-Fa-f]{4})$").find(base)?.let { return String(Character.toChars(it.groupValues[1].toInt(16))) }
        Regex("^u([0-9A-Fa-f]{4,6})$").find(base)?.let {
            val cp = it.groupValues[1].toInt(16)
            if (Character.isValidCodePoint(cp)) return String(Character.toChars(cp))
        }
        return null
    }
